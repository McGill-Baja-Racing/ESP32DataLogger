#!/bin/sh
# Regenerates src/ui/fonts/archivo_*.c, the fonts built into the program.
#
# Archivo is under the SIL Open Font License (src/ui/fonts/OFL.txt). The fonts are cut
# down to the characters below to keep the program small. To add a character, add it
# to UNICODES and run this again.
#
# Needs curl, xxd and fontTools: python3 -m pip install fonttools
set -eu
cd "$(dirname "$0")/.."

ARCHIVO_COMMIT=211127690e8ff106c36c935f7e5e697114cff103
# Printable ASCII, degree sign, middle dot, en dash and minus sign.
UNICODES="U+0020-007E,U+00B0,U+00B7,U+2013,U+2212"
OUT=src/ui/fonts

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

for weight in SemiBold Bold ExtraBold; do
    name=archivo_$(echo "$weight" | tr '[:upper:]' '[:lower:]')
    curl -fsSL -o "$tmp/full.ttf" \
        "https://raw.githubusercontent.com/Omnibus-Type/Archivo/$ARCHIVO_COMMIT/fonts/ttf/Archivo-$weight.ttf"
    pyftsubset "$tmp/full.ttf" --unicodes="$UNICODES" --layout-features=kern --no-hinting \
        --output-file="$tmp/subset.ttf"
    {
        echo "/* Generated by tools/make_fonts.sh: Archivo $weight, cut down. SIL Open Font License 1.1. */"
        echo '#include "dd_fonts.h"'
        echo
        echo "const unsigned char dd_${name}_ttf[] = {"
        xxd -i < "$tmp/subset.ttf"
        echo "};"
        echo "const unsigned int dd_${name}_ttf_len = sizeof(dd_${name}_ttf);"
    } > "$OUT/$name.c"
    echo "$OUT/$name.c: $(wc -c < "$tmp/subset.ttf") bytes of font"
done
